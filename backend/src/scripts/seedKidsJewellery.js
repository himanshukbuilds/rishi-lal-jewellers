async function seedKidsJewellery() {
  console.log('[Seed Kids] Connecting to MongoDB...');
  await mongoose.connect(MONGODB_URI || 'mongodb://127.0.0.1:27017/rishi_lal_jewellers');
  console.log('[Seed Kids] Connected to MongoDB.');

  // 1. Correct any legacy misplaced product
  await Product.updateOne(
    { sku: 'AUR-DIA-ER-006' },
    { $set: { gender: 'women' } }
  );
  console.log('[Seed Kids] Preserved AUR-DIA-ER-006 in women diamond catalog.');

  // 2. Remove only old Kids-specific products
  // Keep Men, Women, Wedding, Gifting, Bangles, Necklaces etc. strictly untouched.
  const oldKidsDeleteResult = await Product.deleteMany({
    $or: [
      { sku: 'AUR-KID-BG-017' },
      { categorySlug: 'kids', sku: { $nin: kidsProducts.map(p => p.sku) } },
      { category: "Kids' Jewellery", sku: { $nin: kidsProducts.map(p => p.sku) } },
      { gender: 'kids', sku: { $nin: kidsProducts.map(p => p.sku) } }
    ]
  });
  console.log(`[Seed Kids] Removed old Kids-specific records: ${oldKidsDeleteResult.deletedCount}`);

  // 3. Ensure Category document exists for Kids' Jewellery
  await Category.findOneAndUpdate(
    { slug: 'kids' },
    {
      $set: {
        name: "Kids' Jewellery",
        slug: 'kids',
        description: 'Auspicious baby treasures, lightweight 22KT gold balis, protective nazariya cuffs, and 925 sterling silver heirlooms handcrafted with child-safe comfort.',
        image: '/images/gender/kids.jpg',
        featured: true,
        displayOrder: 9
      }
    },
    { upsert: true, new: true }
  );
  console.log('[Seed Kids] Category "Kids\' Jewellery" ensured in Category collection.');

  // 4. Upsert all 30 new products safely and idempotently
  let inserted = 0;
  let updated = 0;

  for (const item of kidsProducts) {
    const existing = await Product.findOne({ sku: item.sku });
    await Product.findOneAndUpdate(
      { sku: item.sku },
      { $set: item },
      { upsert: true, new: true, setDefaultsOnInsert: true }
    );
    if (existing) {
      updated++;
    } else {
      inserted++;
    }
  }

  console.log(`[Seed Kids] Upsert complete: ${inserted} inserted, ${updated} updated.`);

  // 5. Verify MongoDB count
  const count = await Product.countDocuments({
    $or: [{ categorySlug: 'kids' }, { gender: 'kids' }]
  });
  console.log(`[Seed Kids] Total Kids' jewellery products in MongoDB now: ${count}`);

  const sample = await Product.find({ categorySlug: 'kids' }, 'name sku price subcategory images stock isOrderable').limit(5).lean();
  console.log('[Seed Kids] Sample verified records:');
  sample.forEach((p, i) => {
    console.log(`  [${i + 1}] ${p.name} | SKU: ${p.sku} | Price: ₹${p.price} | Stock: ${p.stock} | Orderable: ${p.isOrderable} | Image: ${p.images?.[0]}`);
  });

  await mongoose.disconnect();
  console.log('[Seed Kids] MongoDB disconnected cleanly.');
}

if (require.main === module) {
  seedKidsJewellery().catch(err => {
    console.error('[Seed Kids] Error:', err);
    process.exit(1);
  });
}


async function seedGifting() {
  console.log('Connecting to MongoDB...');
  await mongoose.connect(process.env.MONGODB_URI || 'mongodb://127.0.0.1:27017/rishi_lal_jewellers');
  console.log('Connected to DB:', mongoose.connection.name);

  // 1. Verify all image files exist on disk before DB insertion
  const publicDir = path.resolve(__dirname, '../../../frontend/public');
  const seenSkus = new Set();
  const seenSlugs = new Set();

  for (const item of giftingProducts) {
    if (seenSkus.has(item.sku)) throw new Error(`Duplicate SKU in seed data: ${item.sku}`);
    seenSkus.add(item.sku);

    if (seenSlugs.has(item.slug)) throw new Error(`Duplicate Slug in seed data: ${item.slug}`);
    seenSlugs.add(item.slug);

    for (const img of item.images) {
      const diskPath = path.join(publicDir, img);
      if (!fs.existsSync(diskPath)) {
        throw new Error(`Image path not found on disk: ${diskPath}`);
      }
    }
  }

  console.log(`Validated all ${giftingProducts.length} image paths on disk!`);

  // 2. Upsert each product cleanly
  let inserted = 0;
  let updated = 0;

  for (const item of giftingProducts) {
    const existing = await Product.findOne({ sku: item.sku });
    await Product.findOneAndUpdate(
      { sku: item.sku },
      { $set: item },
      { upsert: true, new: true, setDefaultsOnInsert: true }
    );
    if (existing) {
      updated++;
    } else {
      inserted++;
    }
  }

  console.log(`Upsert complete: ${inserted} inserted, ${updated} updated.`);

  // 3. Query MongoDB to confirm count and presence
  const totalGifting = await Product.countDocuments({ categorySlug: 'gifting' });
  const allGifting = await Product.find({ categorySlug: 'gifting' }, 'name sku price subcategory images').lean();

  console.log(`Verified total Gifting products in MongoDB: ${totalGifting}`);
  console.log('Sample verified records:');
  allGifting.slice(0, 5).forEach((p, idx) => {
    console.log(`  [${idx + 1}] ${p.name} | SKU: ${p.sku} | ₹${p.price} | Image: ${p.images[0]}`);
  });

  await mongoose.disconnect();
  console.log('MongoDB disconnected successfully.');
}

if (require.main === module) {
  seedGifting().catch((err) => {
    console.error('Seed error:', err);
    process.exit(1);
  });
}

module.exports = { giftingProducts, seedGifting };

